/**
 * Form mapping and the payload builders for the Order Detail screen.
 *
 * RN-free on purpose, so the repo's plain-node jest covers it — `jest.config.js` matches
 * `*.test.ts` only, and anything that ends up in a `.tsx` is untestable here by construction.
 *
 * The single most important thing in this file is `toUpdatePayload`. `PUT /{module}Order` is a
 * FULL-OBJECT replace: `GenericOrderService.updateOrder` copies every field off the request onto
 * the record, so a field missing from the request is not "left alone", it is erased. The builder
 * therefore starts from the DTO the server last gave us and overlays the edits.
 *
 * `orderItems` is the field that makes this dangerous rather than merely wrong. The update does
 * `existing.setOrderItems(validated)` with `incoming = newData.getOrderItems() != null ? … :
 * List.of()`, then `reverseRemoved` **restocks every deducted unit** for any product that vanished
 * from the list. Modulex's own comment at `GenericOrderService.java:2029-2037` calls this out as
 * "the exact package-drop class of bug".
 */

import { displayUnitLines, lineTotal, type OrderLine, type UnitLine } from './orderLineUnits';

// Re-exported so the detail screen has one import surface, and so a card and a record can never
// disagree about how money, a date or a status reads.
